for lang_code, keys in NEW_KEYS.items():
    # Find the pattern: goBackGlobal line then }, for this language
    # Each language ends with:  "goBackGlobal": "...",
    # },
    pattern = '  "' + re.escape(lang_code) + '": \{'
    
    # Find the language block start
    match_start = re.search(pattern, content)
    if not match_start:
        print(f"WARNING: Could not find language block for {lang_code}")
        continue
    
    # From the start of this language block, find the closing "goBackGlobal" line
    lang_start = match_start.start()
    
    # Find the next language block or end of the translations object
    # The block ends with:  },\n  "next_lang": or  },\n};
    next_lang_pattern = r'\n  "(?:' + '|'.join(l for l in NEW_KEYS.keys() if l != lang_code) + r')": \{'
    next_match = re.search(next_lang_pattern, content[lang_start + 10:])
    
    if next_match:
        block_end = lang_start + 10 + next_match.start()
    else:
        # Last language - find the closing of the const
        block_end = content.find('\n};', lang_start)
        if block_end == -1:
            print(f"WARNING: Could not find end of translations object for {lang_code}")
            continue
    
    # Find the last }, before the block end
    # The last line of each language block is:  "goBackGlobal": "...",
    # },
    insert_point = content.rfind('},', lang_start, block_end)
    if insert_point == -1:
        print(f"WARNING: Could not find closing for {lang_code}")
        continue
    
    # Build the new keys string
    new_keys_str = '\n'
    for k, v in keys.items():
        new_keys_str += f'    "{k}": "{v}",\n'
    
    # Insert before the closing  },
    content = content[:insert_point] + new_keys_str + content[insert_point:]
    print(f"Added {len(keys)} keys to {lang_code}")

with open(FILE, 'w', encoding='utf-8') as f:
    f.write(content)

