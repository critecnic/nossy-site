const LANGS = ["en","pt-br","pt-pt","es","fr","de","it","nl","pl","ru","zh","ja","ko","hi","bn","ar","tr","vi","th","ur","tl","sw"];

// só insere se a chave não existe no bloco do idioma
function insertKeys() {
  const anchor = src.indexOf('export const i18n');
  if (anchor < 0) throw new Error('export const i18n não encontrado');
  let out = src;
  let inserted = 0;
  // percorre do último idioma para o primeiro para não invalidar índices
  for (const lang of LANGS) {
    const blockStart = out.indexOf(`"${lang}": {`, anchor);
    if (blockStart < 0) throw new Error(`bloco do idioma ${lang} não encontrado`);
    const braceEnd = out.indexOf('}', blockStart);
    const blockBody = out.slice(blockStart, braceEnd);
    const lines = [];
    for (const [key, byLang] of Object.entries(T)) {
      const val = byLang[lang];
      if (val === undefined) continue;
      if (blockBody.includes(`"${key}"`)) continue; // já existe
      lines.push(`    "${key}": ${JSON.stringify(val)},`);
      inserted++;
    }
    if (lines.length) {
      const insertAt = blockStart + `"${lang}": {`.length;
      out = out.slice(0, insertAt) + '\n' + lines.join('\n') + out.slice(insertAt);
    }
  }
  return { out, inserted };
}

const { out, inserted } = insertKeys();
